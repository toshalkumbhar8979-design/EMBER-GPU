"""
tools/gen_sw_data.py — generate sw/scene_data.h + sw/gamestate_words.h:
the 8 temple-triangle vertex blocks (15 fp32 words each, mata-independent)
and the assembled gamestate kernel words, as C hex literals for the
bare-metal host demo (sw/ember_demo.c). Run from the repo root:

    python3 tools/gen_sw_data.py
"""
import os
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "golden"))
sys.path.insert(0, os.path.join(os.path.dirname(__file__)))

import assembler          # noqa: E402
import scene              # noqa: E402
import gamestate as GS    # noqa: E402


def main():
    root = os.path.join(os.path.dirname(__file__), "..")

    base = scene.mvp_fly_words(0.0, 0.0)
    _, v15s = scene.scene_build(base)
    assert len(v15s) == 8, f"expected 8 scene triangles, got {len(v15s)}"

    lines = ["#ifndef SCENE_DATA_H", "#define SCENE_DATA_H",
             "", "/* Generated by tools/gen_sw_data.py — DO NOT EDIT.",
             " * 8 temple triangles x 15 fp32 words (x,y,z,u,v per vertex),",
             " * identical to the v15 blocks tb_fly/tb_input feed GSX. */",
             "#define SCENE_TRIS 8",
             "static const unsigned int scene_v15[SCENE_TRIS * 15] = {"]
    for t, v15 in enumerate(v15s):
        lines.append(f"  /* tri {t} */")
        for i in range(0, 15, 5):
            words = ", ".join(f"0x{w & 0xFFFFFFFF:08x}u" for w in v15[i:i + 5])
            lines.append(f"  {words},")
    lines += ["};", "", "#endif /* SCENE_DATA_H */"]
    out = os.path.join(root, "sw", "scene_data.h")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(v15s)} triangles -> {out}")

    kpath = os.path.join(root, "kernels", "gamestate.asm")
    kwords = assembler.run_assembler(open(kpath).read())
    lines = ["#ifndef GAMESTATE_WORDS_H", "#define GAMESTATE_WORDS_H",
             "", "/* Generated by tools/gen_sw_data.py — DO NOT EDIT.",
             f" * kernels/gamestate.asm assembled ({len(kwords)} words). */",
             "#define GAMESTATE_NWORDS "
             f"{len(kwords)}",
             "static const unsigned int gamestate_words[GAMESTATE_NWORDS] = {"]
    for i in range(0, len(kwords), 6):
        words = ", ".join(f"0x{w & 0xFFFFFFFF:08x}u"
                          for w in kwords[i:i + 6])
        lines.append(f"  {words},")
    lines += ["};", "", "#endif /* GAMESTATE_WORDS_H */"]
    out = os.path.join(root, "sw", "gamestate_words.h")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(kwords)} kernel words -> {out}")

    inp, _path = GS.demo_script()
    assert len(inp) == 32
    lines = ["#ifndef DEMO_INPUTS_H", "#define DEMO_INPUTS_H", "",
             "/* Generated by tools/gen_sw_data.py — DO NOT EDIT.",
             " * The 32-frame input script (mirrors gamestate.demo_inputs). */",
             "#define DEMO_FRAMES 32",
             "static const signed char demo_ax[DEMO_FRAMES] = {",
             "  " + ", ".join(str(int(ax)) for ax, _ in inp) + ",",
             "};",
             "static const signed char demo_az[DEMO_FRAMES] = {",
             "  " + ", ".join(str(int(az)) for _, az in inp) + ",",
             "};", "", "#endif /* DEMO_INPUTS_H */"]
    out = os.path.join(root, "sw", "demo_inputs.h")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(inp)} input frames -> {out}")

    # exact base MVP words (f32m of mvp_fly_words(0,0)) + the SX constant
    # AS IEEE-754 DOUBLE bits, so the C host folds row0[3] bit-identically
    # to the Python golden (no libc printf/strtod rounding drift):
    import struct as _s
    basem = list(scene.mvp_fly_words(0.0, 0.0))   # already f32m flat words
    assert len(basem) == 16
    sx_d = _s.unpack("<Q", _s.pack("<d", float(scene.SX)))[0]
    lines = ["#ifndef MVP_BASE_H", "#define MVP_BASE_H", "",
             "/* Generated by tools/gen_sw_data.py — DO NOT EDIT.",
             " * f32m(mvp_fly_words(0,0)) — row0[3]/row3[3] patched per frame. */",
             "static const unsigned int mvp_base[16] = {"]
    for i in range(0, 16, 4):
        lines.append("  " + ", ".join(
            f"0x{w & 0xFFFFFFFF:08x}u" for w in basem[i:i + 4]) + ",")
    lines += ["};",
              f"#define SX_DOUBLE_BITS 0x{sx_d:016x}ULL",
              "#define ROW0_BASE_480_F32 0x{0:08x}u".format(basem[3]),
              "", "#endif /* MVP_BASE_H */"]
    out = os.path.join(root, "sw", "mvp_base.h")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"base MVP + SX bits -> {out}")


if __name__ == "__main__":
    main()
