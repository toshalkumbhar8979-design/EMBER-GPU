#!/usr/bin/env python3
"""die_plan.py -- floorplan the integrated GPU die.

Band layout (avoids rows-under-macros entirely):
  [margin ring]
  [macro band 2: rtr_top xbar display cp]     (aligned at band bottom)
  [channel]
  [macro band 1: core tu gsx blit]            (aligned at band bottom)
  [channel]
  [core band: std-cell rows for the 253 glue cells]

All macro positions are band-bottom-aligned so power straps cross the die
vertically (met4) and horizontally (met5) and land on the boundary stubs the
macro LEFs expose. Channels give the router room for the AXI/fpa buses.

Inputs : build/gds/<block>/gds_validation.json  (width_um / height_um)
Outputs: build/gds/die/die_plan.json  {die, macros, bands}
         build/gds/die/die_plan.tcl   (initialize_floorplan + place_macro cmds)
"""
import json
from pathlib import Path

BAND2 = ["rtr_top", "xbar", "display", "cp"]
BAND1 = ["core", "tu", "gsx", "blit"]
MARGIN = 25.0
CHAN = 60.0     # vertical channel between bands
GAP = 40.0      # horizontal gap between macros inside a band
CORE_H = 300.0  # glue-cell band height

root = Path("/work/build/gds")
sizes = {}
for b in BAND1 + BAND2:
    vj = root / b / "gds_validation.json"
    if not vj.exists():
        raise SystemExit(f"missing {vj} -- harden {b} first")
    d = json.loads(vj.read_text())
    sizes[b] = (float(d["width_um"]), float(d["height_um"]))
    print(f"{b:10s} {sizes[b][0]:8.1f} x {sizes[b][1]:8.1f} um")

h1 = max(sizes[b][1] for b in BAND1)
h2 = max(sizes[b][1] for b in BAND2)
w_used = max(sum(sizes[b][0] for b in BAND1) + GAP * (len(BAND1) - 1),
             sum(sizes[b][0] for b in BAND2) + GAP * (len(BAND2) - 1))
die_w = MARGIN + w_used + MARGIN
die_h = MARGIN + h1 + CHAN + h2 + CHAN + CORE_H + MARGIN

inst = {"core": "u_core", "tu": "u_tu", "gsx": "u_gsx", "blit": "u_blit",
        "rtr_top": "u_rtr", "xbar": "u_xbar", "display": "u_disp", "cp": "u_cp"}

macros = {}
y2 = MARGIN                      # band 2 sits at the bottom
x = MARGIN
for b in BAND2:
    w, h = sizes[b]
    macros[b] = {"x": round(x, 3), "y": round(y2, 3), "w": w, "h": h}
    x += w + GAP
y1 = MARGIN + h2 + CHAN          # band 1 above band 2
x = MARGIN
for b in BAND1:
    w, h = sizes[b]
    macros[b] = {"x": round(x, 3), "y": round(y1, 3), "w": w, "h": h}
    x += w + GAP
core_y1 = y1 + h1 + CHAN
core_y2 = core_y1 + CORE_H

plan = {"die": {"w": round(die_w, 3), "h": round(die_h, 3)},
        "bands": {"macro2_y": y2, "macro1_y": y1,
                  "core_y1": round(core_y1, 3), "core_y2": round(core_y2, 3)},
        "macros": macros, "block_to_inst": inst}
out = root / "die"
out.mkdir(parents=True, exist_ok=True)
(out / "die_plan.json").write_text(json.dumps(plan, indent=1))

tcl = f"""# generated by die_plan.py -- do not edit
initialize_floorplan -die_area {{0 0 {die_w} {die_h}}} \\
    -core_area {{{MARGIN} {core_y1} {die_w - MARGIN} {core_y2}}} -site unithd
make_tracks
proc place_ember_macro {{inst_name x y}} {{
  set block [ord::get_db_block]
  set inst [$block findInst $inst_name]
  if {{$inst == "NULL"}} {{ error "macro instance $inst_name not found" }}
  $inst setOrient R0
  $inst setOrigin [expr int(round($x * 1000))] [expr int(round($y * 1000))]
  $inst setPlacementStatus FIRM
  puts "placed $inst_name at ($x, $y)"
}}
"""
for b, m in macros.items():
    tcl += f"place_ember_macro {inst[b]} {m['x']} {m['y']}\n"
(out / "die_plan.tcl").write_text(tcl)
print(f"die {die_w:.1f} x {die_h:.1f} um = {die_w*die_h/1e6:.2f} mm^2")
print(f"core band y: {core_y1:.1f}..{core_y2:.1f} -> {out}")
