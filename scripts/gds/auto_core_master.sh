#!/usr/bin/env bash
# auto_core_master.sh -- unattended overnight controller (session-independent).
#
# USER POLICY (explicit, 2026-10-19):
#   * NEVER touch the running core OpenROAD. Wait/poll only.
#   * If and only if DRT completes all 40 passes AND violations remain:
#     RESUME routing from the routed checkpoint with a higher iteration cap.
#     Resume only -- no rebuild, no re-synthesis, nothing else.
#   * When routing is clean (or a resume round stops making progress), run the
#     final GDS tail exactly as finish_core_from_routed.sh does:
#     Magic merge + flattened DRC -> KLayout finalize -> export audit ->
#     verify_block core.
#   * After core verifies, restart the block queue fresh (run_cached.sh KEEPs
#     every audited block) so rtr_scan -> rtr_top -> die run unattended;
#     chip_watch.sh (already running) composes chip.gds when die lands.
#
# Detached via setsid; survives session end / Freebuff session close.
# Single instance via flock. Status log: /work/build/gds/OVERNIGHT_STATUS.log
set -u
export PATH="$HOME/.local/emberbin:$PATH"
# PAUSE_BUILD: user-requested stop (2026-10-20). No auto-resume until the
# marker is removed: rm /work/build/gds/PAUSE_BUILD
if [ -f /work/build/gds/PAUSE_BUILD ]; then
  echo "PAUSE_BUILD marker present; auto_core_master not starting (user request)" >> /work/build/gds/OVERNIGHT_STATUS.log
  exit 0
fi
DIR=/work/build/gds/core
LOG=/work/build/gds/OVERNIGHT_STATUS.log
say() { echo "== $(date '+%F %T') == $*"; }
exec >>"$LOG" 2>&1
say "auto_core_master start pid=$$"
exec 9>/work/build/gds/.auto_core_master.lock
flock -n 9 || { say "another auto_core_master active; exiting"; exit 0; }

cd "$DIR" || { say "core dir missing"; exit 1; }
viol() { grep -oE 'Number of violations = [0-9]+' "$1" 2>/dev/null | tail -1 | grep -oE '[0-9]+$'; }

# ---- 1. wait for the REAL OpenROAD binary to exit -------------------------
# (pgrep must not match the frozen `timeout 86400 openroad ...` wrapper, which
# stays alive SIGSTOPped; only the /bin/openroad process is the router.)
if ! pgrep -f '/bin/openroad -no_init -exit floorplan\.tcl' >/dev/null \
   && [ ! -s final.def ] && [ ! -s openroad.log ]; then
  say "no core routing run found at all (no log, no final.def); nothing to do"
  exit 0
fi
while pgrep -f '/bin/openroad -no_init -exit floorplan\.tcl' >/dev/null; do sleep 60; done
say "core OpenROAD exited (floorplan.tcl)."
sleep 5

ITERS=$(grep -cE 'optimization iteration' openroad.log 2>/dev/null | tail -1)
ITERS=${ITERS:-0}
VIOL=$(viol openroad.log)
say "exit state: drt_iters=$ITERS violations=${VIOL:-?} final.def=$([ -s final.def ] && echo yes || echo NO) final.odb=$([ -s final.odb ] && echo yes || echo NO)"

# The routed checkpoint is the source of truth when openroad.log lost its DRT
# evidence (an aborted rebuild attempt truncated it on 2026-10-19). Recover
# the DEF from its byte-identical backup if missing, and resume from the
# checkpoint regardless of what the clobbered log reports -- NEVER rebuild.
if [ ! -s final.def ] && [ -s final_iter40_backup.def ]; then
  cp -p final_iter40_backup.def final.def && say "restored final.def from final_iter40_backup.def"
fi
if [ -s final.odb ] || [ -s final.def ]; then
  # Checkpoint presence is the authority that 40 DRT passes completed.
  [ "${ITERS:-0}" -lt 40 ] && ITERS=40
  if [ -z "${VIOL:-}" ]; then
    VIOL=$(grep -oE 'Number of violations = [0-9]+' /work/build/gds/PRE_SHUTDOWN_STATUS.log 2>/dev/null | tail -1 | grep -oE '[0-9]+$')
    VIOL=${VIOL:-152}
    say "openroad.log lacks DRT evidence (clobbered); routed checkpoint present -> resume-only, seeded violations=$VIOL"
  fi
fi

# Freeze the queue chain BEFORE anything unwinds, so a dying harden script
# cannot be recorded as a core failure.
RC=$(pgrep -f 'run_cached\.sh' | head -1); [ -n "${RC:-}" ] && kill -STOP "$RC" 2>/dev/null && say "paused queue pid=$RC"
HD=$(pgrep -f 'harden_physical_snapshot\.sh core' | head -1); [ -n "${HD:-}" ] && kill -9 "$HD" 2>/dev/null && say "stopped core harden shell pid=$HD (GDS tail is taken over here)"
WRAP=$(pgrep -f '^timeout 86400 openroad' | head -1); [ -n "${WRAP:-}" ] && kill -9 "$WRAP" 2>/dev/null && say "removed frozen timebox wrapper pid=$WRAP"

# ---- 2/3. RESUME routing iff 40 passes completed and violations remain ----
ROUND=0
PREV=$VIOL
while [ "${VIOL:-0}" != "0" ] && [ "${ITERS:-0}" -ge 40 ] && [ "$ROUND" -lt 6 ]; do
  ROUND=$((ROUND+1))
  say "RESUME round $ROUND: continue detailed routing from routed checkpoint (cap +60 iters, resume-only) violations=$VIOL"
  [ "$ROUND" = 1 ] && [ -f final.def ] && cp -f final.def final_iter40_backup.def 2>/dev/null
  cat > route_resume.tcl <<'TCL'
# route_resume.tcl -- RESUME detailed routing from the routed checkpoint.
# Generated by auto_core_master.sh. No synthesis, no floorplan, no placement.
read_liberty /home/toshal/.volare/volare/sky130/versions/fa87f8f4bbcc7255b6f0c0fb506960f531ae2392/sky130A/libs.ref/sky130_fd_sc_hd/lib/sky130_fd_sc_hd__tt_025C_1v80.lib
read_lef /home/toshal/.volare/volare/sky130/versions/fa87f8f4bbcc7255b6f0c0fb506960f531ae2392/sky130A/libs.ref/sky130_fd_sc_hd/techlef/sky130_fd_sc_hd__nom.tlef
read_lef /home/toshal/.volare/volare/sky130/versions/fa87f8f4bbcc7255b6f0c0fb506960f531ae2392/sky130A/libs.ref/sky130_fd_sc_hd/lef/sky130_fd_sc_hd.lef
if {[file exists final.odb]} {
  read_db final.odb
  puts "RESUME_SOURCE=final.odb"
} else {
  read_verilog synth.v
  link_design ember_core
  read_def final.def
  puts "RESUME_SOURCE=final.def"
}
set_thread_count 8
set_routing_layers -signal met2-met5 -clock met2-met5
detailed_route -bottom_routing_layer met1 -top_routing_layer met5 -output_drc route_drc_resume.rpt -droute_end_iter 60 -verbose 1
write_db final_new.odb
write_def final_new.def
write_verilog final_nl.v
puts "RESUME_ROUND_DONE"
TCL
  openroad -no_init -exit route_resume.tcl > "openroad_resume_${ROUND}.log" 2>&1
  RRC=$?
  # Keep openroad.log as the cumulative routing evidence: verify_block.py and
  # post-reboot gate decisions read it, so append each resume round's real log.
  cat "openroad_resume_${ROUND}.log" >> openroad.log
  RV=$(viol "openroad_resume_${ROUND}.log")
  say "resume round $ROUND rc=$RRC violations=${RV:-?}"
  if [ -s final_new.def ]; then
    mv -f final_new.odb final.odb 2>/dev/null || true
    mv -f final_new.def final.def 2>/dev/null || true
    say "routed checkpoint updated after round $ROUND"
  fi
  if [ -z "${RV:-}" ]; then
    say "resume round $ROUND produced no DRT result (router refused resume); stopping resume"
    grep -iE 'error|usage' "openroad_resume_${ROUND}.log" | head -3 | while read -r l; do say "  resume log: $l"; done
    break
  fi
  if [ "$RV" -ge "${PREV:-999999}" ] && [ "$ROUND" -gt 1 ]; then
    say "resume round $ROUND made no progress ($PREV -> $RV); stopping resume"
    break
  fi
  PREV=$VIOL
  VIOL=$RV
done
[ "$ROUND" -gt 0 ] && say "resume phase finished after $ROUND round(s): violations=${VIOL:-?}"
if [ "${VIOL:-1}" != "0" ]; then
  echo "violations=${VIOL:-?} iters=${ITERS} rounds=$ROUND $(date)" > /work/build/gds/CORE_NEEDS_ATTENTION
fi

# ---- 4. GDS tail: identical steps to finish_core_from_routed.sh -----------
PDK=$(ls -d "$HOME"/.volare/volare/sky130/versions/*/sky130A 2>/dev/null | head -1)
[ -n "$PDK" ] || { say "PDK NOT FOUND"; exit 3; }
NAME=core; TOP=ember_core; DEF=final.def
[ -s "$DEF" ] || { say "NO final.def: routing never completed; nothing touched"; exit 3; }
cat > .magicrc <<EOF
set PDKPATH $PDK
tech load \$PDKPATH/libs.tech/magic/sky130A.tech
scalegrid 1 2
addpath \$PDKPATH/libs.ref/sky130_fd_sc_hd/mag
addpath \$PDKPATH/libs.ref/sky130_fd_sc_hd/maglef
drc euclidean on
EOF
cat > magic.tcl <<EOF
lef read $PDK/libs.ref/sky130_fd_sc_hd/techlef/sky130_fd_sc_hd__nom.tlef
gds read $PDK/libs.ref/sky130_fd_sc_hd/gds/sky130_fd_sc_hd.gds
def read $DEF
load $TOP -dereference
gds write $NAME.gds
flatten ${TOP}_drc_flat
load ${TOP}_drc_flat
select top cell
box select
drc on
drc style drc(full)
drc check
drc catchup
set drcerr [drc list count total]
puts "DRC_DETAILS=[drc listall why]"
puts "DRC_COUNT=\$drcerr"
EOF
say "== magic merge + flattened DRC =="
timeout 43200 magic -rcfile .magicrc -dnull -noconsole magic.tcl > magic.log 2>&1 \
  || say "MAGIC FAIL (falling back to KLayout DEF->GDS)"
grep -m1 DRC_COUNT magic.log || echo "DRC_COUNT=?"
if [ ! -f $NAME.gds ]; then
  say "Magic produced no GDS -> KLayout DEF->GDS fallback"
  PDK="$PDK" KLAYOUT_DEF="$DEF" KLAYOUT_TOP=$TOP KLAYOUT_OUT=$NAME.gds \
    klayout -b -r /work/scripts/gds/def2gds.py > klayout_def.log 2>&1 || true
fi
say "== KLayout finalize =="
KLAYOUT_IN=$NAME.gds KLAYOUT_OUT=${NAME}_final.gds KLAYOUT_TOP=$TOP \
  klayout -b -r /work/scripts/gds/finalize.py > klayout.log 2>&1 \
  || { say "GDS VALIDATION FAILED"; tail -10 klayout.log; exit 2; }
mv "${NAME}_final.gds" "$NAME.gds" || exit 2
ls -la "$NAME.gds"
say "== exported-GDS audit =="
python3 /work/scripts/gds/audit_export.py "$NAME" > export_audit_run.log 2>&1 \
  || { say "EXPORTED GDS AUDIT FAILED"; tail -10 export_audit_run.log; exit 4; }
EDRC=$(python3 -c "import json; print(json.load(open(\"export_audit.json\"))[\"whole_layout_flattened_drc\"])")
RDRC=$(grep "Number of violations =" openroad.log | tail -1)
MDRC=$(grep "^DRC_COUNT=" magic.log | tail -1)
say "audit_drc=$EDRC routing=[$RDRC] magic=[$MDRC]"

if python3 /work/scripts/gds/verify_block.py "$NAME"; then
  say "CORE VERIFIED: final GDS accepted"
  echo "verified $(date)" > /work/build/gds/CORE_FINISH_DONE
  # ---- 5. restart the block queue for the remaining blocks ----------------
  say "restarting block queue (run_cached KEEPs every audited block)"
  for pat in 'recover_1017\.sh' 'run_cached\.sh' 'harden_physical_snapshot\.sh'; do
    for p in $(pgrep -f "$pat"); do kill -9 "$p" 2>/dev/null && say "  stopped stale chain pid=$p"; done
  done
  sleep 3
  setsid nohup bash /work/scripts/gds/run_cached.sh </dev/null >/work/build/gds/run_cached_night.log 2>&1 &
  say "queue relaunched: rtr_scan -> rtr_top -> die (chip_watch composes chip.gds)"
else
  say "CORE NOT VERIFIED: routing=[$RDRC] magic=[$MDRC] audit=$EDRC"
  echo "routing=[$RDRC] magic=[$MDRC] audit=$EDRC $(date)" > /work/build/gds/CORE_FINISH_PARTIAL
fi
say "auto_core_master done"
